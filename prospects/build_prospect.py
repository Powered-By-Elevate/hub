#!/usr/bin/env python3
"""Build a prospect's mock Hub: one company, its brand, sample figures.

    python3 prospects/build_prospect.py <spec.json>      one prospect, into the folder beside its spec
    python3 build.py                                     the demo, then every prospects/<id>/ into dist/<id>/

A prospect has no ledger connected yet, so this is the demo engine pointed at
one company instead of eight: the industry profile is overlaid with the
prospect's own name, entities, units and scale (what the spec's `industry`
block sets), the figures are generated by data/gen.py exactly as the demo's
are, and the build is a single-company Hub (the tenant shape, no chooser) that
keeps the sample-data note on every page.

A prospect whose demo is public (Matt, 2026-11-18: "put all 3 on the github
pages") keeps its spec and brand files in prospects/<id>/ and is built into
the published site at /<id>/. Anything private stays in local-only/. Its keys:

    id           short id, also the brand key
    displayName  the company as the Hub names it
    industry     id of the base industry in config/industries.json
    overlay      deep-merged into that industry (company, entities, unit,
                 pages, headline, kpis, model, unitList, ...)
    brand        a config/brands.json entry; `logo` is a file path, inlined
    notice       the sample note (defaults to the demo's)
    modulesOff   product modules to leave out, e.g. ["people"]
    out          the dist folder to write (defaults beside the spec)
"""
from __future__ import annotations

import base64
import copy
import json
import mimetypes
import sys
from pathlib import Path

HUB = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HUB))
sys.path.insert(0, str(HUB / "data"))

from build import build, _cfg  # noqa: E402
import gen  # noqa: E402


def merge(base, over):
    if isinstance(base, dict) and isinstance(over, dict):
        out = dict(base)
        for k, v in over.items():
            out[k] = merge(base.get(k), v) if k in base else copy.deepcopy(v)
        return out
    return copy.deepcopy(over)


def data_url(path: Path) -> str:
    mime = mimetypes.guess_type(path.name)[0] or "image/png"
    return f"data:{mime};base64,{base64.b64encode(path.read_bytes()).decode()}"


def prospect(spec_path: Path, out: Path | None = None) -> dict:
    spec = json.loads(spec_path.read_text(encoding="utf-8"))
    here = spec_path.parent
    product, brands, inds = _cfg("product"), _cfg("brands"), _cfg("industries")
    conns, roles = _cfg("connectors"), _cfg("roles")
    base = next((i for i in inds["industries"] if i["id"] == spec["industry"]), None)
    if not base:
        raise SystemExit(f"industry {spec['industry']!r} is not in config/industries.json")
    ind = merge(base, spec.get("overlay") or {})
    ind["company"] = spec["displayName"]
    ind["brand"] = spec["id"]
    ind.pop("hidden", None)

    brand = merge(brands["brands"]["default"], spec.get("brand") or {})
    brand.setdefault("name", spec["displayName"])
    for key in ("logo", "logoDark", "logoWide", "hero", "watermark"):
        if brand.get(key) and not str(brand[key]).startswith("data:"):
            brand[key] = data_url((here / brand[key]).resolve())

    for key in spec.get("modulesOff") or []:   # a module the prospect has no use for (HR for a team of five)
        product["modules"].pop(key, None)
    product["tenant"] = {"id": spec["id"], "company": spec["displayName"], "sample": True}
    product["demoNotice"] = spec.get("notice") or product.get("demoNotice", "")

    lift = 0.0
    for _ in range(6):
        try:
            doc = gen.build(ind, product, lift)
            break
        except gen.NeedLift as need:
            lift = need.amount
    else:
        raise SystemExit("could not find an opening equity that keeps cash positive")

    configs = {"product": product, "brands": {**brands, "brands": {spec["id"]: brand}},
               "industries": {**inds, "industries": [ind]}, "connectors": conns, "roles": roles}
    if out is None:
        out = Path(spec.get("out") or here / "dist")
        if not out.is_absolute():
            out = (here / out).resolve()
    return build(no_data=True, dist=out, configs=configs, data={ind["id"]: doc})


def build_all(dist: Path) -> list[str]:
    """Every prospects/<id>/spec.json into dist/<id>/, after the demo is built."""
    done = []
    for spec in sorted((HUB / "prospects").glob("*/spec.json")):
        pid = spec.parent.name
        prospect(spec, dist / pid)
        (dist / pid / ".nojekyll").unlink(missing_ok=True)
        done.append(pid)
    return done


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("usage: python3 prospects/build_prospect.py <spec.json>")
    m = prospect(Path(sys.argv[1]).resolve())
    print(f"built {m['dist']}")
